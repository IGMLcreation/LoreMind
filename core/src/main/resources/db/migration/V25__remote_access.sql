-- Accès distant à l'application de bureau (tablette / téléphone sur le réseau local).
-- remote_access_config : réglage singleton (id = 'current') — activé ou non, port réseau.
-- remote_devices       : appareils appairés par code ; seule l'EMPREINTE SHA-256 du jeton
--                        est stockée (le jeton lui-même ne vit que dans le cookie de l'appareil).
-- Tables présentes partout (Docker compris) mais utilisées uniquement en mode bureau.
-- Compatible Postgres et H2 (MODE=PostgreSQL).
create table remote_access_config (
    id varchar(32) not null,
    enabled boolean not null,
    port integer not null,
    updated_at timestamp(6) with time zone not null,
    primary key (id)
);

create table remote_devices (
    id bigint generated by default as identity,
    name varchar(100) not null,
    token_hash varchar(64) not null,
    user_agent varchar(300),
    created_at timestamp(6) with time zone not null,
    last_seen_at timestamp(6) with time zone,
    primary key (id)
);
create unique index ux_remote_device_token on remote_devices (token_hash);
